async function seed(page: Page, data: TrainingData | string = base) {
  await page.addInitScript(raw => {
    if (!sessionStorage.getItem('training-test-seeded')) {
      localStorage.setItem('cubelab:training:v1', raw)
      sessionStorage.setItem('training-test-seeded','true')
    }
  }, typeof data === 'string' ? data : JSON.stringify(data))
  await page.goto('/')
  await page.getByTestId('training-nav').click()
  await expect(page.getByRole('heading', { name: typeof data === 'string' ? 'Training unavailable' : 'Training Hub', exact: true })).toBeVisible()
}
async function resumeSession(page: Page) {
  await page.getByRole('button', { name: 'Resume session', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Current session' })).toBeVisible()
  await expect(page.locator(TIMER)).toBeEnabled()
}
async function confirmEnd(page: Page) {
  await page.getByRole('region', { name: 'Current session' }).getByRole('button', { name: 'End session', exact: true }).click()
  await page.getByRole('group', { name: 'Confirm end session' }).getByRole('button', { name: 'End session', exact: true }).click()
}
async function endSession(page: Page) {
  const data = await read(page)
  const visit = data.visits.find(item => item.id === data.activeVisitId)!
  await confirmEnd(page)
  if (visit.attemptIds.length) {
    await page.getByRole('dialog', { name: visit.session!.name, exact: true }).getByRole('button', { name: 'Done' }).click()
  }
  await expect(page.getByRole('heading', { name: 'Training Hub' })).toBeVisible()
}
async function activeHistory(visitId: string, durations: readonly number[], prefix: string): Promise<TrainingData> {
  const prepared = { ...await prepareTrainingSetup(base, 'oll:execution', null, 'oll:27'), generatedAt: NOW - 1 }
  const data = beginTrainingSession(base, {
    id: visitId, at: NOW, categoryId: 'oll:execution',
    session: { version: 1, name: 'Seeded OLL', cases: [{ caseId: 'oll:27', algorithm: prepared.generatorAlgorithm }] },
  })
  const attempts = durations.map((rawMs, index) => createTrainingAttempt({
    id: `${prefix}${index}`, visitId, setup: prepared, createdAt: NOW + index, rawMs,
  }))
  const visit = data.visits[0]!
  return { ...data, attempts, visits: [{
    ...visit, attemptIds: attempts.map(a => a.id),
    lifecycle: { ...visit.lifecycle!, lastActivityAt: NOW + attempts.length },
  }] }
}
async function read(page: Page): Promise<TrainingData> { return page.evaluate(() => JSON.parse(localStorage.getItem('cubelab:training:v1')!)) }
async function rejectTrainingWrites(page: Page) {
  await page.evaluate(() => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function (key, value) {
      if (key === 'cubelab:training:v1') throw new DOMException('Synthetic quota failure', 'QuotaExceededError')
      original.call(this, key, value)
    }
    window.addEventListener('restore-training-writes', () => { Storage.prototype.setItem = original }, { once: true })
  })
}
async function restoreTrainingWrites(page: Page) {
  await page.evaluate(() => window.dispatchEvent(new Event('restore-training-writes')))
}
async function start(page: Page) {
  await expect(page.locator(TIMER)).toBeEnabled()
  await page.evaluate(() => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur() })
  await page.keyboard.down('Space')
  await expect(page.locator(TIMER)).toHaveAttribute('data-phase','ready')
  await page.keyboard.up('Space')
  await expect(page.locator(TIMER)).toHaveAttribute('data-phase','running')
}
async function stop(page: Page) {
  await page.keyboard.press('Space')
  await expect(page.locator(TIMER)).toHaveAttribute('data-phase','idle')
}
async function attempt(page: Page) { await start(page); await page.waitForTimeout(80); await stop(page) }
async function begin(page: Page) { await page.getByRole('button',{name:'Begin training',exact:true}).click(); await expect(page.getByTestId('training-scramble')).toBeVisible() }
async function openTrainingSettings(page: Page) {
  await page.getByTestId('settings-button').click()
  return page.getByRole('dialog', { name: 'Settings' })
}
async function openStatisticsOptions(page: Page) {
  await page.getByRole('button', { name: 'Statistics options', exact: true }).click()
}
async function calibrate(page: Page) {
  for (let i = 0; i < 7; i++) { await attempt(page); await page.getByRole('button',{name:'Keep sample',exact:true}).click() }
  await expect(page.locator(TIMER)).toBeEnabled()
}

